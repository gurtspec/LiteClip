# LiteClip build script.
# Builds LiteClip.exe from the source code in .\src using the C# compiler that ships with Windows
# (no Visual Studio, no NuGet packages, no third-party code), then downloads FFmpeg from its
# official build repository and verifies it against the published SHA-256 checksum.
#
# Usage (in PowerShell, inside this folder):
#   powershell -ExecutionPolicy Bypass -File .\build.ps1
#
# Result: .\dist\LiteClip.exe  (+ .\dist\tools\ffmpeg.exe, ffprobe.exe, .\dist\lang\)
# To make the release zip afterwards: .\package.ps1

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$dist = Join-Path $root 'dist'
$tools = Join-Path $dist 'tools'
New-Item -ItemType Directory -Force $dist, $tools | Out-Null

# ---- 1. Compile ---------------------------------------------------------------------------
$fw = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319'
$csc = Join-Path $fw 'csc.exe'
if (-not (Test-Path $csc)) { throw "The .NET Framework C# compiler was not found at $csc" }

# App icon (drawn here so the repository contains no binary files)
Add-Type -AssemblyName System.Drawing
$icoPath = Join-Path $dist 'LiteClip.ico'
$bmp = New-Object System.Drawing.Bitmap 64, 64
$g = [System.Drawing.Graphics]::FromImage($bmp); $g.SmoothingMode = 'AntiAlias'; $g.Clear([System.Drawing.Color]::Transparent)
$g.FillEllipse((New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(20, 20, 20))), 2, 2, 60, 60)
$g.DrawEllipse((New-Object System.Drawing.Pen ([System.Drawing.Color]::FromArgb(240, 240, 240)), 5), 8, 8, 48, 48)
$g.FillEllipse((New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(255, 77, 77))), 21, 21, 22, 22)
$g.Dispose()
$ico = [System.Drawing.Icon]::FromHandle($bmp.GetHicon()); $fs = [IO.File]::Create($icoPath); $ico.Save($fs); $fs.Close()

$refs = @(
  "$fw\WPF\PresentationFramework.dll", "$fw\WPF\PresentationCore.dll", "$fw\WPF\WindowsBase.dll", "$fw\System.Xaml.dll",
  "$fw\System.Windows.Forms.dll", "$fw\System.Drawing.dll", "$fw\System.Management.dll",
  "$fw\Microsoft.VisualBasic.dll", "$fw\Microsoft.CSharp.dll", "$fw\System.Core.dll", "$fw\System.dll"
) | ForEach-Object { "/r:$_" }
$xaml = Get-ChildItem (Join-Path $root 'src\ui') -Filter *.xaml | ForEach-Object { "/resource:$($_.FullName),LiteClip.ui.$($_.Name)" }
$sources = Get-ChildItem (Join-Path $root 'src') -Filter *.cs | ForEach-Object { $_.FullName }
$exe = Join-Path $dist 'LiteClip.exe'

Write-Host "Compiling LiteClip..." -ForegroundColor Cyan
& $csc /nologo /target:winexe /optimize+ /nowarn:618 "/out:$exe" "/win32icon:$icoPath" @refs @xaml @sources
if ($LASTEXITCODE -ne 0) { throw "Compile failed." }

# ---- 2. Languages ----------------------------------------------------------------------------
# lang\template.txt lists every text in the app, so anyone can translate LiteClip without reading code.
$langSrc = Join-Path $root 'lang'
New-Item -ItemType Directory -Force $langSrc | Out-Null
$seen = New-Object 'System.Collections.Generic.HashSet[string]'
$lines = New-Object 'System.Collections.Generic.List[string]'
$lines.Add('# LiteClip translation template (made by build.ps1, do not edit this file).')
$lines.Add('# To translate: copy this file, name it after your language (e.g. Spanish.txt), and write each')
$lines.Add('# translation after the "=>". Lines you leave empty stay in English. Keep {0}, {1} and \n as they are.')
$lines.Add('language => ')
$sources = @(Get-ChildItem (Join-Path $root 'src\ui') -Filter *.xaml) + @(Get-ChildItem (Join-Path $root 'src') -Filter *.cs)
foreach ($f in $sources) {
  $code = [IO.File]::ReadAllText($f.FullName)
  if ($f.Extension -eq '.xaml') {
    $texts = [regex]::Matches($code, '(?:Text|Content|ToolTip)="([^"{][^"]*)"') | ForEach-Object { [System.Net.WebUtility]::HtmlDecode($_.Groups[1].Value) } | Where-Object { $_ -match '\p{L}' }
  } else {
    $texts = [regex]::Matches($code, 'L\.T\("((?:[^"\\]|\\.)*)"') | ForEach-Object { $_.Groups[1].Value.Replace('\"', '"').Replace('\\', '\') }
  }
  $new = @($texts | Where-Object { $seen.Add($_) })
  if ($new.Count -eq 0) { continue }
  $lines.Add(''); $lines.Add("# ---- $($f.Name)")
  foreach ($t in $new) { $lines.Add("$t => ") }
}
[IO.File]::WriteAllLines((Join-Path $langSrc 'template.txt'), $lines, (New-Object System.Text.UTF8Encoding $false))
$langDist = Join-Path $dist 'lang'
New-Item -ItemType Directory -Force $langDist | Out-Null
Copy-Item (Join-Path $langSrc '*.txt') $langDist -Force
Write-Host "Languages: $($seen.Count) texts in lang\template.txt" -ForegroundColor Cyan

# ---- 3. FFmpeg (official BtbN build, LGPL), verified by SHA-256 ---------------------------
if (-not (Test-Path (Join-Path $tools 'ffmpeg.exe'))) {
  $base = 'https://github.com/BtbN/FFmpeg-Builds/releases/download/latest'
  $zip = 'ffmpeg-n8.1-latest-win64-lgpl-8.1.zip'
  $tmp = Join-Path $env:TEMP 'liteclip-ffmpeg'; New-Item -ItemType Directory -Force $tmp | Out-Null
  Write-Host "Downloading FFmpeg from github.com/BtbN/FFmpeg-Builds ..." -ForegroundColor Cyan
  $ProgressPreference = 'SilentlyContinue'
  Invoke-WebRequest "$base/checksums.sha256" -OutFile "$tmp\checksums.sha256" -UseBasicParsing
  Invoke-WebRequest "$base/$zip" -OutFile "$tmp\$zip" -UseBasicParsing
  $expected = ((Get-Content "$tmp\checksums.sha256") | Where-Object { $_ -match [regex]::Escape($zip) }) -split '\s+' | Select-Object -First 1
  $actual = (Get-FileHash "$tmp\$zip" -Algorithm SHA256).Hash.ToLower()
  if (-not $expected -or $expected -ne $actual) { throw "FFmpeg checksum mismatch! expected $expected, got $actual. Not using it." }
  Write-Host "FFmpeg checksum OK: $actual" -ForegroundColor Green
  Expand-Archive "$tmp\$zip" "$tmp\x" -Force
  $bin = (Get-ChildItem "$tmp\x" -Recurse -Filter ffmpeg.exe | Select-Object -First 1).DirectoryName
  Copy-Item "$bin\ffmpeg.exe", "$bin\ffprobe.exe" $tools -Force
  Copy-Item (Get-ChildItem "$tmp\x" -Recurse -Filter LICENSE.txt | Select-Object -First 1).FullName (Join-Path $tools 'FFMPEG-LICENSE.txt') -Force
  Remove-Item $tmp -Recurse -Force
}

# ---- 4. Fingerprints ------------------------------------------------------------------------
Write-Host "`nBuilt: $exe" -ForegroundColor Green
foreach ($f in @($exe, (Join-Path $tools 'ffmpeg.exe'), (Join-Path $tools 'ffprobe.exe'))) {
  "{0,-14} SHA-256 {1}" -f (Split-Path $f -Leaf), (Get-FileHash $f -Algorithm SHA256).Hash
}
